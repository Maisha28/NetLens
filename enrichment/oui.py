"""
MAC address -> device hints, fully offline.

Two independent facts can be read from a MAC without any lookup service:

  * Locally-administered bit (bit 1 of the first byte). When set, the address
    was generated by software, not burned in by a manufacturer. Modern phones
    do this on purpose ("private Wi-Fi address") so a device cannot be tracked
    across networks - which also means such a MAC carries no vendor info.
  * OUI (the first three bytes) - the IEEE-assigned manufacturer prefix. Only
    a small hand-curated table is bundled, like the IP range table: enough to
    label common gear, honest ("Unknown vendor") about everything else.
"""

from __future__ import annotations

from typing import Optional

OUI_VENDORS = {
    "00:03:93": "Apple", "00:0a:95": "Apple", "00:0d:93": "Apple", "00:11:24": "Apple",
    "00:0c:f1": "Intel", "00:1b:21": "Intel", "00:02:b3": "Intel", "00:03:47": "Intel",
    "24:0a:c4": "Espressif (IoT)", "30:ae:a4": "Espressif (IoT)", "24:6f:28": "Espressif (IoT)",
    "b8:27:eb": "Raspberry Pi", "dc:a6:32": "Raspberry Pi",
    "00:12:fb": "Samsung", "00:15:99": "Samsung",
    "3c:5a:b4": "Google", "f4:f5:d8": "Google", "94:eb:2c": "Google",
    "00:0c:29": "VMware", "00:50:56": "VMware",
    "00:15:5d": "Microsoft (Hyper-V)", "00:50:f2": "Microsoft",
    "00:00:0c": "Cisco",
}


def is_randomized(mac: Optional[str]) -> bool:
    try:
        return bool(int(mac.split(":")[0], 16) & 0x02)
    except (AttributeError, ValueError):
        return False


def vendor(mac: Optional[str]) -> str:
    if not mac:
        return ""
    if mac.lower() == "ff:ff:ff:ff:ff:ff":
        return "Broadcast"
    if is_randomized(mac):
        return "Private (randomised) address"
    return OUI_VENDORS.get(mac.lower()[:8], "Unknown vendor")
